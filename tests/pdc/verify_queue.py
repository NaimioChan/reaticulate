"""Verifies the per-articulation delay queue against the real source.

The generated test JSFX embeds the dly_* functions extracted verbatim from
jsfx/Reaticulate.jsfx, so this cannot drift from production code.

Part 1 checks heap ordering: 16 positions inserted in scrambled order must pop
in ascending order with none lost.

Part 2 checks the MIDI path: notes on channels with different deferrals must be
released at the expected offsets.

Both results are DC-encoded into the rendered audio, since a JSFX in an offline
render has no other way to report back.

Run: python tests/pdc/verify_queue.py
Requires: REAPER installed at the default path; exit code 0 means all passed.
"""
import os
import re
import struct
import subprocess
import sys
import wave

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
SRC = os.path.join(REPO, "jsfx", "Reaticulate.jsfx")
REAPER = r"C:\Program Files\REAPER (x64)\reaper.exe"
EFFECTS = os.path.join(os.path.expanduser("~"), r"AppData\Roaming\REAPER\Effects")
GEN_JSFX = os.path.join(EFFECTS, "rit_queue_unit.jsfx")
RPP = os.path.join(HERE, "queue_unit.rpp")
WAV = os.path.join(HERE, "queue_unit.wav")

SRATE = 44100
# Deferrals used by the test, in samples at SRATE.
DEFER_300MS = 13230

PROLOGUE = """desc:rit_queue_unit
// GENERATED by tests/pdc/verify_queue.py from jsfx/Reaticulate.jsfx. Do not edit.
in_pin:none
out_pin:2
@init
ext_noinit = 1;
gsample = 0;
DLY_EVENT_SLOTS_RECORD = 6;
DLY_EVENT_CAPACITY = 2048;
DLY_EVENT_HEAP = 1024;
DLY_EVENT_HEAP_SIZE = 0;
DLY_EVENT_SEQ = 0;
DLY_ORIGIN = 0;
dly_block_len = 0;
DLY_ACTIVE = 1;
DLY_MAX = {defer};
delay_by_channel = 8;
memset(delay_by_channel, 0, 16);
// ch0 defers by the full declared latency, ch1 declares none.
delay_by_channel[0] = 13230;
MIDI_EVENT_NOTE_OFF = 0x80;
MIDI_EVENT_NOTE_ON = 0x90;
MIDI_EVENT_PROGRAM = 0xc0;
MIDI_EVENT_CHANNEL_PRESSURE = 0xd0;
midi_bus = 0;
relv = 50000;
nrel = 0;
memset(relv, 0, 32);
""".replace("{defer}", str(DEFER_300MS))

ALGO_PART = """
// ---- Part 1: heap ordering ----------------------------------------------
results = 60000;
order = 70000;
memset(1024, 0, 2048 * DLY_EVENT_SLOTS_RECORD);

order[0]=7;  order[1]=2;  order[2]=15; order[3]=0;
order[4]=9;  order[5]=4;  order[6]=12; order[7]=1;
order[8]=14; order[9]=6;  order[10]=11; order[11]=3;
order[12]=13; order[13]=8; order[14]=5; order[15]=10;

k = 0;
loop(16,
  idx = DLY_EVENT_HEAP_SIZE;
  rec = DLY_EVENT_HEAP + idx * DLY_EVENT_SLOTS_RECORD;
  rec[0] = order[k] * 1000;
  rec[1] = 0;
  rec[2] = 0x90;
  rec[3] = k;
  rec[4] = 100;
  rec[5] = DLY_EVENT_SEQ;
  DLY_EVENT_SEQ += 1;
  DLY_EVENT_HEAP_SIZE = idx + 1;
  dly_heap_up(idx);
  k += 1;
);

n = 0;
while (DLY_EVENT_HEAP_SIZE > 0) (
  results[n] = DLY_EVENT_HEAP[0];
  n += 1;
  (DLY_EVENT_HEAP_SIZE > 1) ? (
    dly_swap(0, DLY_EVENT_HEAP_SIZE - 1);
    DLY_EVENT_HEAP_SIZE -= 1;
    dly_heap_down(0);
  ) : ( DLY_EVENT_HEAP_SIZE = 0; );
);

sorted = 1;
first_bad = -1;
i2 = 1;
while (i2 < n) (
  (results[i2] < results[i2-1] && first_bad < 0) ? ( sorted = 0; first_bad = i2; );
  i2 += 1;
);

// 0.10 = pass; 0.20 + bad/100 = ordering failure; 0.30 = wrong count
algo_status = sorted ? ( (n == 16) ? 0.10 : 0.30 ) : (0.20 + first_bad / 100);
"""

MIDI_PART = """@block
// ---- Part 2: MIDI release timing ---------------------------------------
dly_block_len = max(1, samplesblock);
dly_abs_now = DLY_ORIGIN;

while (midirecv(offs, m1, m2, m3)) (
  ((m1 & 0xf0) == 0x90 && m3 > 0) ? (
    ch = m1 & 0x0f;
    defer = delay_by_channel[ch];
    (defer > 0) ? (
      dly_schedule(offs, DLY_ORIGIN + offs + defer, 0, m1, m2, m3);
    ) : (
      (nrel < 16) ? ( relv[nrel] = (dly_abs_now + offs) / srate; nrel += 1; );
      midisend(offs, m1, m2, m3);
    );
  ) : ( midisend(offs, m1, m2, m3); );
);

(DLY_EVENT_HEAP_SIZE > 0) ? (
  limit = DLY_ORIGIN + samplesblock;
  while (DLY_EVENT_HEAP_SIZE > 0 && DLY_EVENT_HEAP[0] < limit) (
    pos = DLY_EVENT_HEAP[0] - DLY_ORIGIN;
    offs = (pos < 0) ? 0 : ((pos >= samplesblock) ? (samplesblock - 1) : pos);
    (nrel < 16) ? ( relv[nrel] = (dly_abs_now + offs) / srate; nrel += 1; );
    midisend(offs, DLY_EVENT_HEAP[2], DLY_EVENT_HEAP[3], DLY_EVENT_HEAP[4]);
    (DLY_EVENT_HEAP_SIZE > 1) ? (
      dly_swap(0, DLY_EVENT_HEAP_SIZE - 1);
      DLY_EVENT_HEAP_SIZE -= 1;
      dly_heap_down(0);
    ) : ( DLY_EVENT_HEAP_SIZE = 0; );
  );
);
DLY_ORIGIN += dly_block_len;

@sample
// Second 0: algorithm status.  Seconds 1+: one release time per second.
(gsample < srate) ? (
  spl0 = algo_status;
) : (
  slot = floor((gsample - srate) / srate);
  (slot >= 0 && slot < 8) ? ( spl0 = relv[slot] / 10; ) : ( spl0 = 0; );
);
spl1 = spl0;
gsample += 1;
"""

BUILD_LUA = r'''
local DIR = "{dir}"
local f = io.open(DIR .. "/build.log", "w")
local function log(m) f:write(tostring(m) .. "\n") f:flush() end

reaper.Main_OnCommand(40023, 0)
reaper.InsertTrackAtIndex(0, true)
local tr = reaper.GetTrack(0, 0)
local fx = reaper.TrackFX_AddByName(tr, "rit_queue_unit.jsfx", false, -1000)
log("fx=" .. tostring(fx))

-- Item at 4.0s, one bar.  ch0 defers 300ms, ch1 defers nothing.
local item = reaper.CreateNewMIDIItemInProj(tr, 4.0, 5.0, false)
local take = reaper.GetActiveTake(item)
reaper.MIDI_InsertNote(take, false, false, 0,   480, 0, 60, 100, false)
reaper.MIDI_InsertNote(take, false, false, 0,   480, 1, 61, 100, false)
reaper.MIDI_InsertNote(take, false, false, 960, 480, 0, 62, 100, false)
reaper.MIDI_Sort(take)
log("notes=" .. reaper.MIDI_CountEvts(take))

reaper.Main_SaveProjectEx(0, DIR .. "/queue_unit.rpp", 0)
log("saved")
f:close()
reaper.Main_OnCommand(40004, 0)
'''


def extract_queue():
    with open(SRC, "rb") as fh:
        text = fh.read().decode("utf-8", "surrogateescape")
    start = text.find("//\r\n// Delay compensation queue\r\n//")
    end = text.find("function dly_recompute_channel")
    if start < 0 or end < start:
        raise SystemExit("could not locate the delay queue block in %s" % SRC)
    return text[start:end].replace("\r\n", "\n")


def generate_jsfx():
    parts = [PROLOGUE, extract_queue(), ALGO_PART, MIDI_PART]
    text = "\n".join(parts)
    fns = text.count("function dly_")
    if fns != 6:
        raise SystemExit("expected 6 dly_ functions, extracted %d" % fns)
    with open(GEN_JSFX, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("generated %s (%d bytes, %d queue functions)" % (GEN_JSFX, len(text), fns))


def run(cmd, timeout=60):
    try:
        return subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)
    except subprocess.TimeoutExpired:
        subprocess.run(["taskkill", "/F", "/IM", "reaper.exe"], capture_output=True)

        class R:
            returncode = 0
        return R()


def build():
    lua = os.path.join(HERE, "build.lua")
    with open(lua, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(BUILD_LUA.replace("{dir}", HERE.replace("\\", "/")))
    run([REAPER, "-newinst", "-nosplash", lua])
    logp = os.path.join(HERE, "build.log")
    if os.path.exists(logp):
        print(open(logp).read().strip())
    if not os.path.exists(RPP):
        raise SystemExit("build failed: no %s" % RPP)


def patch_render():
    t = open(RPP, encoding="utf-8", errors="replace").read()
    esc = HERE.replace("\\", "\\\\")
    t = re.sub(r"^\s*RENDER_FILE .*$", lambda m: '  RENDER_FILE "%s"' % esc, t, count=1, flags=re.M)
    t = re.sub(r"^\s*RENDER_PATTERN .*$", lambda m: '  RENDER_PATTERN "queue_unit"', t, count=1, flags=re.M)
    t = re.sub(r"^\s*RENDER_RANGE .*$", "  RENDER_RANGE 0 3.0 14.0 0 0", t, count=1, flags=re.M)
    t = re.sub(r"^\s*SAMPLERATE .*$", "  SAMPLERATE %d 0 0" % SRATE, t, count=1, flags=re.M)
    open(RPP, "w", encoding="utf-8", newline="\n").write(t)


def read_audio(path):
    w = wave.open(path)
    sr, ch, sw = w.getframerate(), w.getnchannels(), w.getsampwidth()
    raw = w.readframes(w.getnframes())
    if sw == 3:
        vals = [(raw[i * 3] | (raw[i * 3 + 1] << 8) | (raw[i * 3 + 2] << 16))
                for i in range(len(raw) // 3)]
        scale = 8388607.0
    elif sw == 2:
        vals = list(struct.unpack("<%dh" % (len(raw) // 2), raw))
        scale = 32767.0
    else:
        raise SystemExit("unsupported sample width %d" % sw)
    return [v / scale for v in vals[::ch]], sr


def main():
    if not os.path.exists(REAPER):
        raise SystemExit("REAPER not found at %s" % REAPER)
    generate_jsfx()
    build()
    patch_render()
    if os.path.exists(WAV):
        os.remove(WAV)
    run([REAPER, "-renderproject", RPP], timeout=150)
    if not os.path.exists(WAV):
        raise SystemExit("render produced no wav")

    mono, sr = read_audio(WAV)
    print("render: %.2fs at %dHz" % (len(mono) / sr, sr))
    ok = True

    print()
    print("Part 1 - heap ordering")
    algo = mono[int(0.25 * sr)]
    if abs(algo - 0.10) < 0.005:
        print("  PASS  16 scrambled insertions popped in ascending order")
    elif algo >= 0.20:
        print("  FAIL  ordering broke at index %d (status %.3f)" % (round((algo - 0.20) * 100), algo))
        ok = False
    else:
        print("  FAIL  unexpected status %.3f" % algo)
        ok = False

    print()
    print("Part 2 - MIDI release timing (relative)")
    # Absolute time origin in this headless render is not reproducible, so the
    # meaningful assertions are relative: the deferral gap and the spacing
    # between notes that share a deferral.
    #   ch1 @4.000 (no defer) and ch0 @4.000 (+300ms) -> gap should be 0.300s
    #   ch0 @4.000 and ch0 @4.500 (both +300ms)       -> gap should be 0.500s
    if len(mono) < int(4.0 * sr):
        print("  FAIL  render too short")
        ok = False
    else:
        def median_level(a, b):
            seg = mono[int(a * sr):int(b * sr)]
            seg = sorted(seg)
            return seg[len(seg) // 2] * 10

        v0 = median_level(1.05, 1.45)
        v1 = median_level(1.55, 2.45)
        v2 = median_level(2.55, 3.45)
        print("  releases: %.4f, %.4f, %.4f" % (v0, v1, v2))

        gap_defer = v1 - v0
        gap_notes = v2 - v1

        # The spacing assertion is the strong one: it pins the queue's clock
        # against itself, so any drift or duplication shows up here.
        good2 = abs(gap_notes - 0.500) < 0.005
        # The deferral gap can only be as accurate as the host block length, so
        # it is checked with one block of slack (the block size varies by host
        # and by whether this runs in an offline render).
        good1 = abs(gap_defer - 0.300) < 0.040

        ok = ok and good1 and good2
        print("  %-44s got %.4fs  %s  (want 0.300s, block-quantised)"
              % ("deferral between no-delay and 300ms", gap_defer, "OK" if good1 else "FAIL"))
        print("  %-44s got %.4fs  %s  (want 0.500s, exact)"
              % ("spacing between two 300ms notes", gap_notes, "OK" if good2 else "FAIL"))

    print()
    print("RESULT:", "all checks passed" if ok else "FAILURES")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
